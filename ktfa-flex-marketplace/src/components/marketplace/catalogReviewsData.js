/**
 * Récupère les avis certifiés du catalogue pour un produit donné.
 * Si le produit est un nouvel arrivage ou un produit personnalisé,
 * retourne STRICTEMENT un tableau vide [] (aucun faux avis).
 */
export function getCatalogReviews(product) {
  if (!product || !product.id) return [];
  const prodId = String(product.id);
  return SPECIFIC_CATALOG_REVIEWS[prodId] || [];
}

/**
 * Calcule le nombre total d'avis synchronisé entre la carte et le détail
 */
export function getSynchronizedReviewsCount(product) {
  if (!product || !product.id) return 0;
  
  // 1. Avis catalogue spécifiques (uniquement si produit par défaut, sinon 0)
  const catReviews = getCatalogReviews(product);
  
  // 2. Avis réels clients enregistrés en LocalStorage / D1
  let realCount = 0;
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem(`ktfa_reviews_${product.id}`);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed)) realCount = parsed.length;
      }
    } catch (e) {}
  }

  return catReviews.length + realCount;
}
